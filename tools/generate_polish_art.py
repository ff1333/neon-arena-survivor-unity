S = 4

def sprite(name, draw_fn):
    image = Image.new("RGBA", (128*S,128*S))
    draw = ImageDraw.Draw(image)
    def poly(points, fill, outline=None, width=2):
        pts = [(int(x*S),int(y*S)) for x,y in points]
        draw.polygon(pts,fill=fill)
        if outline: draw.line(pts+[pts[0]],fill=outline,width=width*S,joint="curve")
    def ellipse(box,fill): draw.ellipse(tuple(int(v*S) for v in box),fill=fill)
    draw_fn(poly,ellipse)
    image.resize((128,128),Image.Resampling.LANCZOS).save(OUT/(name+".png"))

